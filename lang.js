function setCookie(name, value, days) {
  let expires = "";
  if (days) {
    const date = new Date();
    date.setTime(date.getTime() + days * 24 * 60 * 60 * 1000);
    expires = "; expires=" + date.toUTCString();
  }
  document.cookie = name + "=" + (value || "") + expires + "; path=/; SameSite=Lax";
}

function getCookie(name) {
  const nameEQ = name + "=";
  const ca = document.cookie.split(';');
  for (let i = 0; i < ca.length; i++) {
    let c = ca[i];
    while (c.charAt(0) === ' ') c = c.substring(1, c.length);
    if (c.indexOf(nameEQ) === 0) return c.substring(nameEQ.length, c.length);
  }
  return null;
}

function getCurrentLang() {
  return getCookie('siddhi_lang') || 'en';
}

function applyLanguage(lang) {
  const data = translations[lang] || translations.en;

  // Translate all text elements
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (data[key]) {
      el.innerHTML = data[key];
    }
  });

  // Translate input placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (data[key]) {
      el.setAttribute('placeholder', data[key]);
    }
  });

  // Sync founder card dynamic WhatsApp link
  const founderBtn = document.getElementById('founderWaBtn');
  if (founderBtn && data.about_founder_wa_msg) {
    founderBtn.href = `https://wa.me/918055227005?text=${encodeURIComponent(data.about_founder_wa_msg)}`;
  }

  // Sync footer select dropdown
  const footerSelect = document.getElementById('footerLangSelect');
  if (footerSelect) footerSelect.value = lang;

  setCookie('siddhi_lang', lang, 30);

  // If currently in detail view, refresh current product detail in the new language
  if (window.currentActiveProductId && typeof window.openProductDetail === 'function') {
    window.openProductDetail(window.currentActiveProductId);
  }
}

function selectLanguage(lang) {
  applyLanguage(lang);
  const modal = document.getElementById('langModalOverlay');
  if (modal) modal.style.display = 'none';
}

document.addEventListener('DOMContentLoaded', () => {
  const savedLang = getCookie('siddhi_lang');
  const modal = document.getElementById('langModalOverlay');

  if (savedLang) {
    applyLanguage(savedLang);
    if (modal) modal.style.display = 'none';
  } else {
    applyLanguage('en');
    if (modal) modal.style.display = 'flex';
  }
});
